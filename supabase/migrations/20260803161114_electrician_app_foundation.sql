create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public, anon, authenticated;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'organizations', 'organization_members', 'customers', 'properties',
    'technicians', 'jobs', 'blackout_periods', 'service_settings',
    'estimates', 'invoices', 'inventory_items'
  ]
  loop
    execute format(
      'create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name,
      table_name
    );
  end loop;
end;
$$;

create function private.is_org_member(target_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and exists (
      select 1
      from public.organization_members membership
      where membership.organization_id = target_organization_id
        and membership.user_id = (select auth.uid())
    );
$$;

create function private.is_org_admin(target_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and exists (
      select 1
      from public.organization_members membership
      where membership.organization_id = target_organization_id
        and membership.user_id = (select auth.uid())
        and membership.role in ('owner', 'admin')
    );
$$;

create function private.can_manage_members(target_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and (
      exists (
        select 1
        from public.organizations organization
        where organization.id = target_organization_id
          and organization.created_by = (select auth.uid())
      )
      or exists (
        select 1
        from public.organization_members membership
        where membership.organization_id = target_organization_id
          and membership.user_id = (select auth.uid())
          and membership.role in ('owner', 'admin')
      )
    );
$$;

revoke all on all functions in schema private from public, anon;
grant execute on function private.is_org_member(uuid) to authenticated;
grant execute on function private.is_org_admin(uuid) to authenticated;
grant execute on function private.can_manage_members(uuid) to authenticated;

alter table public.organizations enable row level security;
alter table public.organization_members enable row level security;

create policy "Members can view organizations"
on public.organizations for select
to authenticated
using ((select private.is_org_member(id)));

create policy "Users can create organizations"
on public.organizations for insert
to authenticated
with check (created_by = (select auth.uid()));

create policy "Admins can update organizations"
on public.organizations for update
to authenticated
using ((select private.is_org_admin(id)))
with check ((select private.is_org_admin(id)));

create policy "Owners can delete organizations"
on public.organizations for delete
to authenticated
using (
  exists (
    select 1 from public.organization_members membership
    where membership.organization_id = id
      and membership.user_id = (select auth.uid())
      and membership.role = 'owner'
  )
);

create policy "Members can view organization memberships"
on public.organization_members for select
to authenticated
