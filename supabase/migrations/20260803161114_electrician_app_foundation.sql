create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  timezone text not null default 'America/Los_Angeles',
  base_city text,
  base_state text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz
);

create table public.organization_members (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'admin', 'dispatcher', 'technician', 'accountant')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, user_id)
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  customer_type text not null default 'residential' check (customer_type in ('residential', 'commercial')),
  first_name text,
  last_name text,
  company_name text,
  email text,
  phone text,
  preferred_contact text check (preferred_contact in ('phone', 'sms', 'email')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  check (first_name is not null or last_name is not null or company_name is not null)
);

create table public.properties (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  customer_id uuid not null references public.customers(id) on delete cascade,
  label text not null default 'Primary property',
  address_line_1 text not null,
  address_line_2 text,
  city text not null,
  state text not null,
  postal_code text not null,
  latitude numeric(9, 6),
  longitude numeric(9, 6),
  access_notes text,
  safety_notes text,
  panel_location text,
  panel_manufacturer text,
  service_amperage integer check (service_amperage is null or service_amperage > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz
);

create table public.technicians (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  display_name text not null,
  phone text,
  color text not null default '#FFBF18',
  start_location_type text not null default 'shop' check (start_location_type in ('shop', 'home', 'custom')),
  end_location_type text not null default 'shop' check (end_location_type in ('shop', 'home', 'custom', 'none')),
  skills text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, user_id)
);

create table public.jobs (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  customer_id uuid references public.customers(id) on delete set null,
  property_id uuid references public.properties(id) on delete set null,
  technician_id uuid references public.technicians(id) on delete set null,
  job_number bigint generated by default as identity,
  status text not null default 'draft' check (status in ('draft', 'awaiting_payment', 'confirmed', 'needs_review', 'assigned', 'en_route', 'arrived', 'in_progress', 'completed', 'canceled', 'no_show', 'rescheduled')),
  category text not null default 'diagnostic',
  priority text not null default 'standard' check (priority in ('standard', 'emergency', 'after_hours')),
  customer_description text,
  ai_summary text,
  safety_flags text[] not null default '{}',
  scheduled_start timestamptz,
  scheduled_end timestamptz,
  arrival_window_start timestamptz,
  arrival_window_end timestamptz,
  route_locked boolean not null default false,
  diagnostic_fee_cents integer not null default 10000 check (diagnostic_fee_cents >= 0),
  diagnostic_paid boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  check (scheduled_end is null or scheduled_start is null or scheduled_end > scheduled_start),
  unique (organization_id, job_number)
);

create table public.blackout_periods (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  technician_id uuid not null references public.technicians(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  block_type text not null default 'hard' check (block_type in ('hard', 'flexible', 'private')),
  reason text,
  recurrence_rule text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

